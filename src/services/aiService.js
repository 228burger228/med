import { detectRedFlagsInText, sanitizeText } from "../utils/security";

/**
 * Локальная клиническая классификация травмы/операции (работает мгновенно, без утечки PHI в сторонние облака без прокси)
 */
export function classifyInjuryLocally(text) {
  const t = (text || "").toLowerCase().replace(/ё/g, "е");
  if (
    t.includes("колен") ||
    t.includes("мениск") ||
    t.includes("пкс") ||
    t.includes("крестообраз") ||
    t.includes("надколен")
  ) {
    return {
      part: "Колено",
      explanation:
        "Распознана реабилитация коленного сустава (связочный аппарат / мениск / эндопротезирование). Включён контроль разгибания и активации квадрицепса.",
    };
  }
  if (
    t.includes("плеч") ||
    t.includes("ротатор") ||
    t.includes("манжет") ||
    t.includes("ключиц") ||
    t.includes("акроми") ||
    t.includes("вывих плеч")
  ) {
    return {
      part: "Плечо",
      explanation:
        "Распознана реабилитация плечевого пояса. План сфокусирован на мягкой декомпрессии и плавном возврате амплитуды без импинджмента.",
    };
  }
  if (
    t.includes("спин") ||
    t.includes("позвон") ||
    t.includes("поясниц") ||
    t.includes("грыж") ||
    t.includes("протруз") ||
    t.includes("остеохондр")
  ) {
    return {
      part: "Спина",
      explanation:
        "Распознана реабилитация позвоночника и мышц кора. Подобраны упражнения без осевой перегрузки и с контролем нейтральной поясницы.",
    };
  }
  if (
    t.includes("голеностоп") ||
    t.includes("лодыжк") ||
    t.includes("ахилл") ||
    /(?<![а-я])стоп[аыуе]/.test(t) ||
    t.includes("подвернул ногу")
  ) {
    return {
      part: "Голеностоп",
      explanation:
        "Распознана реабилитация голеностопного сустава и стопы. Акцент на лимфодренаже, тыльном сгибании и проприоцепции.",
    };
  }
  if (
    t.includes("рук") ||
    t.includes("перелом") ||
    t.includes("гипс") ||
    t.includes("запяст") ||
    t.includes("лучев") ||
    /(?<![а-я])кист[ьи](?![а-я])/.test(t) ||
    t.includes("предплеч")
  ) {
    return {
      part: "Перелом руки",
      explanation:
        "Распознана реабилитация верхней конечности после перелома/иммобилизации. Включены противоотёчные и мобилизационные упражнения.",
    };
  }
  return null;
}

/**
 * Классификация описания травмы: серверный прокси (если задан VITE_API_PROXY_URL),
 * иначе локальный поиск по ключевым словам. Всегда проверяет «красные флаги».
 */
export async function analyzeInjuryDescription(rawDescription) {
  const cleanText = sanitizeText(rawDescription, 600);
  const redFlag = detectRedFlagsInText(cleanText);

  // Имитация небольшой задержки анализа для плавного UX
  await new Promise((r) => setTimeout(r, 300));

  const proxyUrl = import.meta.env.VITE_API_PROXY_URL;
  if (proxyUrl) {
    try {
      const res = await fetch(`${proxyUrl}/api/v1/rehab/classify`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ description: cleanText }),
      });
      if (res.ok) {
        const data = await res.json();
        if (data?.part) return { ...data, redFlag };
      }
    } catch {
      // Переход на локальный клинический классификатор
    }
  }

  const localMatch = classifyInjuryLocally(cleanText);
  if (localMatch) {
    return { ...localMatch, redFlag };
  }

  return { part: null, explanation: null, redFlag };
}

/**
 * Справочный помощник на основе правил (не языковая модель): отвечает по ключевым словам,
 * проверяет «красные флаги» и учитывает профиль пациента.
 */
export async function generateClinicalAiReply(userText, injuryProfile) {
  const clean = sanitizeText(userText, 600);
  const redFlag = detectRedFlagsInText(clean);

  await new Promise((r) => setTimeout(r, 350));

  if (redFlag) {
    return `🚨 ${redFlag.title}: ${redFlag.message} Список опасных симптомов — по кнопке SOS в верхней панели.`;
  }

  const t = clean.toLowerCase();
  const partInfo = injuryProfile?.part ? ` (с учётом вашей категории «${injuryProfile.part}», ${injuryProfile.phase?.toLowerCase() || "текущая"} фаза)` : "";

  if (t.includes("амплитуд") || t.includes("rom")) {
    return `Амплитуда движения (Range of Motion, ROM) — это угол в градусах, на который сустав может безопасно согнуться и разогнуться${partInfo}. В реабилитации мы сначала восстанавливаем пассивную и безболезненную активную амплитуду, и только затем добавляем силовую нагрузку. Не форсируйте движение через резкую боль.`;
  }

  if (t.includes("щёлка") || t.includes("щелка") || t.includes("хруст") || t.includes("крепитац")) {
    return `Безболезненные мягкие щелчки или похрустывание (крепитация)${partInfo} часто возникают из-за пузырьков газа в синовиальной жидкости или временного дисбаланса тонуса мышц. Если щелчок НЕ сопровождается резкой болью, отёком или ощущением «заклинивания» сустава — это обычно вариант нормы. При боли или блоке обратитесь к врачу.`;
  }

  if (t.includes("питани") || t.includes("еда") || t.includes("белок") || t.includes("коллаген") || t.includes("витамин")) {
    return `Для ускорения регенерации тканей${partInfo} важны 3 правила: 1) Достаточно белка (1.4–1.8 г на кг веса в сутки — рыба, птица, яйца, творог, бобовые); 2) Овощи и фрукты с витамином C — он нужен для синтеза коллагена; 3) Достаточное питьё (ориентир около 30 мл/кг, если врач не ограничивал жидкость). Добавки обсуждайте с врачом.`;
  }

  if (t.includes("сон") || t.includes("спать") || t.includes("бессонниц") || t.includes("ночью")) {
    return `Сон 7–9 часов важен для восстановления: на глубокий сон приходится основной выброс гормона роста, а недосып усиливает боль. Если сустав ноет ночью, попробуйте уложить конечность на мягкую подушку для лёгкого возвышения и разгрузки связок, а за 1 час до сна проветрите комнату.`;
  }

  if (t.includes("отек") || t.includes("отёк") || t.includes("припух")) {
    return `Умеренный отёк после нагрузки — частая реакция в период реабилитации${partInfo}. Помогает возвышенное положение конечности, мягкие лимфодренажные движения (например, «насос» стопой или кистью) и охлаждение через ткань на 10–15 минут (если одобрено врачом). Если отёк резко нарос, стал горячим и плотным — обратитесь к врачу.`;
  }

  if (t.includes("бол") || t.includes("болит") || t.includes("обезбол")) {
    return `Ориентируйтесь на «светофор боли»: дискомфорт до 3/10 во время упражнения допустим, если он проходит в течение часа после разминки. Если боль достигает 5–6/10 — уменьшите амплитуду и число повторений вдвое. При боли 7–10/10 остановите тренировку и проконсультируйтесь со специалистом.`;
  }

  return `По вашему вопросу${partInfo}: главное правило безопасной реабилитации — регулярность, плавный темп без рывков и контроль самочувствия на следующее утро. Если хотите, уточните: вас интересует техника упражнений, контроль отёка, сон/питание или расшифровка медицинского термина из выписки? Мои ответы — справочные и не заменяют консультацию лечащего врача.`;
}
